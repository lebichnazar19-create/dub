"""Модель полотна (polotno.py) без Kivy: координати, дотик/тягнення,
квадрати, код функцій."""

import pytest

import polotno
from polotno import Полотно

Ш, В = 400, 800


def полотно(**kw):
    п = Полотно(**kw)
    п.вікно(0, 0, Ш, В)
    return п


def дотик(п, x, y):
    п.дотик_униз(x, y)
    return п.дотик_вгору(x, y)


def тягнути(п, від, до, кроків=4):
    п.дотик_униз(*від)
    for i in range(1, кроків + 1):
        п.дотик_рух(від[0] + (до[0] - від[0]) * i / кроків, від[1] + (до[1] - від[1]) * i / кроків)
    return п.дотик_вгору(*до)


# ---- вікно, ядро посередині -----------------------------------------------------

def test_ядро_посередині_вікна_без_гортання():
    п = полотно()
    (ядро,) = п.квадрати()
    assert ядро["тип"] == "ядро" and ядро["підпис"] == "програма"
    assert (ядро["x"] + ядро["розмір"] / 2, ядро["y"] + ядро["розмір"] / 2) == (Ш / 2, В / 2)


def test_ядро_лишається_посередині_коли_вікно_змінює_розмір():
    п = полотно()
    п.вікно(0, 0, 1000, 600)
    (ядро,) = п.квадрати()
    assert (ядро["x"] + ядро["розмір"] / 2, ядро["y"] + ядро["розмір"] / 2) == (500, 300)


def test_вікно_не_в_нулі_зсуває_все():
    п = Полотно()
    п.вікно(10, 20, Ш, В)
    assert п.на_екран(0, 0) == (10 + Ш / 2, 20 + В / 2)
    assert п.з_екрана(*п.на_екран(7, -3)) == (7, -3)


# ---- що в точці ----------------------------------------------------------------

def test_що_в_точці_ядро_межі_включно():
    п = полотно(розмір_ядра=100)
    assert п.що_в_точці(200, 400) == ("ядро", None)
    assert п.що_в_точці(150, 350) == ("ядро", None)
    assert п.що_в_точці(250, 450) == ("ядро", None)
    assert п.що_в_точці(149.9, 400) is None
    assert п.що_в_точці(200, 450.1) is None


def test_новіша_функція_поверх_старішої():
    п = полотно(розмір_функції=100)
    п.функції = [{"x": 0, "y": -200, "код": ""}, {"x": 20, "y": -200, "код": ""}]
    assert п.що_в_точці(200, 200) == ("функція", 1)
    assert п.що_в_точці(160, 200) == ("функція", 0)


def test_функція_поверх_ядра():
    п = полотно()
    п.функції = [{"x": 0, "y": 0, "код": ""}]
    assert п.що_в_точці(200, 400) == ("функція", 0)


# ---- дотик ---------------------------------------------------------------------

def test_дотик_на_порожнє_додає_функцію_в_точці_дотику():
    п = полотно()
    assert дотик(п, 50, 700) == ("додано", 0)
    assert п.функції == [{"x": 50 - Ш / 2, "y": 700 - В / 2, "код": ""}]
    кв = п.квадрати()[1]
    assert (кв["x"] + кв["розмір"] / 2, кв["y"] + кв["розмір"] / 2) == (50, 700)
    assert кв["колір"] == polotno.КОЛІР_ФУНКЦІЇ and кв["підпис"] == "функція"


def test_дотик_на_функцію_відкриває_її():
    п = полотно()
    дотик(п, 50, 700)
    assert дотик(п, 60, 690) == ("відкрити", 0)
    assert len(п.функції) == 1


def test_дотик_на_ядро_нічого_не_робить():
    п = полотно()
    assert дотик(п, Ш / 2, В / 2) is None
    assert п.функції == []


def test_дотик_враховує_гортання():
    п = полотно()
    п.зсув = (30, -40)
    дотик(п, 100, 100)
    assert п.функції[0]["x"] == 100 - Ш / 2 - 30
    assert п.функції[0]["y"] == 100 - В / 2 + 40


def test_відпускання_без_натискання_і_рух_без_натискання():
    п = полотно()
    assert п.дотик_вгору(10, 10) is None
    assert п.дотик_рух(10, 10) is False
    п.дотик_униз(10, 10)
    п.дотик_скасовано()
    assert п.дотик_вгору(10, 10) is None
    assert п.функції == []


# ---- тягнення ------------------------------------------------------------------

def test_тремтіння_в_межах_порога_це_ще_дотик():
    п = полотно(поріг_руху=10)
    п.дотик_униз(50, 50)
    assert п.дотик_рух(55, 55) is False
    assert п.дотик_рух(57, 57) is False      # ≈ 9.9 px від початку
    assert п.зсув == (0, 0)
    assert п.дотик_вгору(57, 57) == ("додано", 0)


def test_тягнення_порожнього_гортає_полотно_без_стрибка():
    п = полотно(поріг_руху=10)
    п.дотик_униз(50, 50)
    assert п.дотик_рух(50, 70) is True        # перший зсув — від самого початку
    assert п.зсув == (0, 20)
    assert п.дотик_рух(50, 100) is True
    assert п.зсув == (0, 50)
    assert п.дотик_вгору(60, 100) is None    # тягнення — не дотик, функція не додається
    assert п.зсув == (10, 50)
    assert п.функції == []
    (ядро,) = п.квадрати()
    assert (ядро["x"] + ядро["розмір"] / 2, ядро["y"] + ядро["розмір"] / 2) == (Ш / 2 + 10, В / 2 + 50)


def test_тягнення_ядра_гортає_полотно():
    п = полотно()
    assert тягнути(п, (Ш / 2, В / 2), (Ш / 2 + 100, В / 2)) is None
    assert п.зсув == (100, 0)
    assert п.функції == []


def test_тягнення_функції_пересуває_лише_її():
    п = полотно()
    дотик(п, 100, 100)
    дотик(п, 300, 100)
    assert тягнути(п, (100, 100), (150, 250)) is None
    assert п.зсув == (0, 0)
    assert len(п.функції) == 2
    кв = п.квадрати()[1]
    assert (кв["x"] + кв["розмір"] / 2, кв["y"] + кв["розмір"] / 2) == (150, 250)
    кв2 = п.квадрати()[2]
    assert (кв2["x"] + кв2["розмір"] / 2, кв2["y"] + кв2["розмір"] / 2) == (300, 100)


def test_після_пересування_функція_відкривається_на_новому_місці():
    п = полотно()
    дотик(п, 100, 100)
    тягнути(п, (100, 100), (150, 250))
    assert дотик(п, 100, 100) == ("додано", 1)
    assert дотик(п, 150, 250) == ("відкрити", 0)


# ---- код -----------------------------------------------------------------------

def test_код_лишається_з_функцією():
    п = полотно()
    дотик(п, 100, 100)
    assert п.код(0) == ""
    п.записати_код(0, 'друкуй("привіт")\n')
    тягнути(п, (100, 100), (200, 200))
    assert п.код(0) == 'друкуй("привіт")\n'
    assert п.квадрати()[1]["код"] == 'друкуй("привіт")\n'


@pytest.mark.parametrize("код, рядок", [
    ("", ""),
    ("\n\n  \n", ""),
    ("\n  x = 1\ny = 2", "x = 1"),
    ("друкуй(\"привіт, світе\")", "друкуй(\"при…"),
    ("123456789012", "123456789012"),
])
def test_перший_рядок(код, рядок):
    assert polotno.перший_рядок(код) == рядок


def test_колір_rgb():
    assert polotno.колір_rgb("#ffffff") == (1, 1, 1)
    assert polotno.колір_rgb("#000000") == (0, 0, 0)
    r, g, b = polotno.колір_rgb(polotno.ФОН)
    assert r > 0.9 and g > 0.9 and 0.7 < b < 0.85     # блідо-жовтий
