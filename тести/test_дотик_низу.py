"""Дотик по всій висоті полотна в застосунку (main.py) — включно з нижнім
краєм і кутами. У Вужі низ полотна був «мертвий»: схований рядок вводу
(висота 0) лежав під полотном і перехоплював дотики. Тут перевіряється
сама розкладка Дуба (під полотном нічого нема) і робота на кожній
висоті: квадрат ставиться, відкривається, пересувається, полотно гортається.

Kivy підроблено (pidrobka_kivy.py) з тими самими правилами розсилання
дотиків, що й у справжньому.
"""

import sys

import pytest

import pidrobka_kivy as kv
from pidrobka_kivy import Дотик, натиснути, рухати, відпустити, торкнутись

Ш, В = 400, 800
X = 40          # далеко від ядра (воно в x 130…270), щоб дотик був на порожнє
ВИСОТИ = [0, 0.5, 1, 2, 5, 10, 30, 50, 100, 400, 700, 790, 798, 799, 800]


@pytest.fixture
def застосунок(monkeypatch):
    kv.встановити(monkeypatch)
    monkeypatch.delitem(sys.modules, "main", raising=False)
    import main
    app = main.ДубApp()
    корінь = app.build()
    корінь.встановити(0, 0, Ш, В)       # як Window: корінь на все вікно
    yield app, корінь
    sys.modules.pop("main", None)


def центр(кв):
    return кв["x"] + кв["розмір"] / 2, кв["y"] + кв["розмір"] / 2


# ---- розкладка: під полотном нічого нема ---------------------------------------------

def test_полотно_єдина_дитина_кореня_і_вкриває_все_вікно(застосунок):
    app, корінь = застосунок
    assert корінь.children == [app.полотно]
    assert app.полотно.children == []
    assert (app.полотно.x, app.полотно.y, app.полотно.width, app.полотно.height) == (0, 0, Ш, В)
    assert app.полотно.top == В
    assert app.полотно.модель.ширина == Ш and app.полотно.модель.висота == В
    assert not app.полотно.disabled


def test_ядро_намальовано_посередині_вікна(застосунок):
    app, корінь = застосунок
    (ядро,) = app.полотно.модель.квадрати()
    assert центр(ядро) == (Ш / 2, В / 2)
    kv.МАЛЮНОК.clear()
    app.полотно.перемалювати()
    прямокутники = [к for к in kv.МАЛЮНОК if к[0] == "прямокутник" and к[3] is None]
    assert прямокутники[0][1:3] == ((0, 0), (Ш, В))          # фон на все полотно
    assert (ядро["x"], ядро["y"]) in [к[1] for к in прямокутники]


# ---- дотик на кожній висоті -------------------------------------------------------

@pytest.mark.parametrize("py", ВИСОТИ)
def test_дотик_на_будь_якій_висоті_ставить_квадрат_саме_там(застосунок, py):
    app, корінь = застосунок
    дотик = торкнутись(корінь, X, py)
    assert дотик.захопили == []          # відпущено
    модель = app.полотно.модель
    assert len(модель.функції) == 1
    assert центр(модель.квадрати()[1]) == (X, py)
    assert корінь.children == [app.полотно]      # редактор не відкрився


@pytest.mark.parametrize("py", ВИСОТИ)
def test_дотик_на_будь_якій_висоті_ловить_саме_полотно(застосунок, py):
    app, корінь = застосунок
    дотик = Дотик(X, py)
    assert натиснути(корінь, дотик)
    assert дотик.захопили == [app.полотно]
    відпустити(корінь, дотик)


@pytest.mark.parametrize("py", ВИСОТИ)
def test_квадрат_на_будь_якій_висоті_відкривається_і_зберігає_код(застосунок, py):
    app, корінь = застосунок
    торкнутись(корінь, X, py)
    торкнутись(корінь, X, py, uid=2)
    assert app.редактор is not None
    assert корінь.children == [app.редактор]
    assert app.полотно not in корінь.children
    assert app.поле_коду.text == ""
    app.поле_коду.text = 'друкуй("низ")\n'
    app.закрити_редактор()
    assert корінь.children == [app.полотно]
    assert app.полотно.модель.код(0) == 'друкуй("низ")\n'
    assert центр(app.полотно.модель.квадрати()[1]) == (X, py)
    # відкривається знову з тим самим кодом
    торкнутись(корінь, X, py, uid=3)
    assert app.поле_коду.text == 'друкуй("низ")\n'


@pytest.mark.parametrize("py", [0, 1, 3, 799, 800])
def test_тягнення_біля_краю_пересуває_квадрат_а_не_ставить_новий(застосунок, py):
    app, корінь = застосунок
    торкнутись(корінь, X, py)
    дотик = Дотик(X, py, uid=2)
    натиснути(корінь, дотик)
    рухати(корінь, дотик, X + 10, py + 20)
    рухати(корінь, дотик, X + 30, py + 60)
    відпустити(корінь, дотик, X + 40, py + 70)
    модель = app.полотно.модель
    assert len(модель.функції) == 1
    assert центр(модель.квадрати()[1]) == (X + 40, py + 70)
    assert корінь.children == [app.полотно]


@pytest.mark.parametrize("py", [0, 1, 799, 800])
def test_тягнення_порожнього_біля_краю_гортає_полотно(застосунок, py):
    app, корінь = застосунок
    дотик = Дотик(30, py)
    натиснути(корінь, дотик)
    рухати(корінь, дотик, 30, 400)
    відпустити(корінь, дотик)
    модель = app.полотно.модель
    assert модель.функції == []
    assert центр(модель.квадрати()[0]) == (Ш / 2, В / 2 + (400 - py))


@pytest.mark.parametrize("x, y", [(0, 0), (Ш, 0), (0, В), (Ш, В)])
def test_кути_вікна_теж_ловлять_дотик(застосунок, x, y):
    app, корінь = застосунок
    торкнутись(корінь, x, y)
    assert центр(app.полотно.модель.квадрати()[1]) == (x, y)


def test_за_межами_полотна_дотик_не_ловиться(застосунок):
    app, корінь = застосунок
    торкнутись(корінь, 200, -1)
    торкнутись(корінь, 200, В + 1, uid=2)
    торкнутись(корінь, -1, 400, uid=3)
    assert app.полотно.модель.функції == []


# ---- редактор ------------------------------------------------------------------------

def test_кнопка_назад_на_android_закриває_редактор_а_не_застосунок(застосунок):
    app, корінь = застосунок
    торкнутись(корінь, 200, 100)
    торкнутись(корінь, 200, 100, uid=2)
    assert app.редактор is not None
    app.поле_коду.text = "x = 1"
    assert kv.Window.клавіша(27) is True
    assert app.редактор is None and корінь.children == [app.полотно]
    assert app.полотно.модель.код(0) == "x = 1"
    assert kv.Window.клавіша(27) is False      # полотно: «Назад» іде далі (вихід)


def test_кнопка_полотно_в_редакторі_повертає_на_полотно(застосунок):
    app, корінь = застосунок
    торкнутись(корінь, 200, 100)
    торкнутись(корінь, 200, 100, uid=2)
    шапка = app.редактор.children[-1]
    кнопка = шапка.children[-1]
    assert кнопка.text == "← Полотно"
    app.поле_коду.text = "y = 2"
    кнопка.натиснути()
    assert корінь.children == [app.полотно]
    assert app.полотно.модель.код(0) == "y = 2"


def test_поле_коду_займає_екран_до_самого_низу(застосунок):
    app, корінь = застосунок
    торкнутись(корінь, 200, 100)
    торкнутись(корінь, 200, 100, uid=2)
    assert app.поле_коду.y == 0 and app.поле_коду.top < В
    дотик = Дотик(200, 0, uid=3)
    assert натиснути(корінь, дотик)
    assert app.поле_коду.focus is True
    assert app.полотно.модель.функції[0]["код"] == ""     # полотно дотик не отримало


def test_після_редактора_полотно_знову_ловить_низ(застосунок):
    app, корінь = застосунок
    торкнутись(корінь, X, 400)
    торкнутись(корінь, X, 400, uid=2)
    app.закрити_редактор()
    assert (app.полотно.x, app.полотно.y, app.полотно.width, app.полотно.height) == (0, 0, Ш, В)
    торкнутись(корінь, 200, 0, uid=3)
    assert len(app.полотно.модель.функції) == 2
    assert центр(app.полотно.модель.квадрати()[2]) == (200, 0)
