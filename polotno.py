"""Полотно Дуба без Kivy: усе, що можна перевірити на комп'ютері.

Координати. «Світ» — нескінченна площина; ядро («програма») стоїть у
точці (0, 0) світу. Полотно показує світ у вікні (x0, y0, ширина, висота —
пікселі, y вгору, як у Kivy): екран = світ + центр вікна + зсув. Зсув
міняється пальцем (гортання), сам центр — коли вікно змінює розмір; тому
без жодного гортання ядро завжди посередині, хоч би яким було вікно.

Дотик. Один палець: натиснув (дотик_униз), рухає (дотик_рух), відпустив
(дотик_вгору). Якщо палець не відійшов від початку далі за поріг_руху —
це дотик, інакше — тягнення. Дотик на порожнє місце додає жовтий квадрат
(функцію) з центром у точці дотику; дотик на функцію — відкриває її
(повертається дія («відкрити», номер)); дотик на ядро — нічого.
Тягнення функції пересуває її, тягнення порожнього місця або ядра гортає
полотно.

Функція — словник {"x", "y", "код"}: центр у світі й текст коду, що
лишається з нею, поки застосунок працює (збереження між запусками — потім).
"""

import math

РОЗМІР_ЯДРА = 140       # px — сторона фіолетового квадрата
РОЗМІР_ФУНКЦІЇ = 100    # px — сторона жовтого квадрата
ПОРІГ_РУХУ = 10         # px — далі за це — тягнення, ближче — дотик

ФОН = "#fff6c8"         # блідо-жовтий
КОЛІР_ЯДРА = "#8a45c0"  # фіолетовий
КОЛІР_ФУНКЦІЇ = "#ffd633"  # жовтий
ПІДПИС_ЯДРА = "програма"
ПІДПИС_ФУНКЦІЇ = "функція"


class Полотно:
    def __init__(self, розмір_ядра=РОЗМІР_ЯДРА, розмір_функції=РОЗМІР_ФУНКЦІЇ, поріг_руху=ПОРІГ_РУХУ):
        self.розмір_ядра = float(розмір_ядра)
        self.розмір_функції = float(розмір_функції)
        self.поріг_руху = float(поріг_руху)
        self.зсув = (0.0, 0.0)          # гортання пальцем, px
        self.вікно_x0 = self.вікно_y0 = 0.0
        self.ширина = self.висота = 0.0
        self.функції = []               # [{"x": …, "y": …, "код": "…"}] — центри у світі
        self._дотик = None              # стан поточного дотику або None

    # ---- вікно й координати -------------------------------------------------

    def вікно(self, x0, y0, ширина, висота):
        """Де на екрані лежить полотно (пікселі Kivy: кут знизу ліворуч)."""
        self.вікно_x0, self.вікно_y0 = float(x0), float(y0)
        self.ширина, self.висота = float(ширина), float(висота)

    @property
    def центр(self):
        return self.вікно_x0 + self.ширина / 2 + self.зсув[0], self.вікно_y0 + self.висота / 2 + self.зсув[1]

    def на_екран(self, x, y):
        cx, cy = self.центр
        return x + cx, y + cy

    def з_екрана(self, sx, sy):
        cx, cy = self.центр
        return sx - cx, sy - cy

    # ---- що де лежить --------------------------------------------------------

    def квадрати(self):
        """Для малювання, знизу вгору: ядро, потім функції за порядком
        додавання (новіша — поверх). Кожен: тип, лівий нижній кут на екрані
        (x, y), розмір, колір, підпис, номер (у функцій) і код."""
        cx, cy = self.на_екран(0, 0)
        п = self.розмір_ядра
        вихід = [{"тип": "ядро", "x": cx - п / 2, "y": cy - п / 2, "розмір": п,
                  "колір": КОЛІР_ЯДРА, "підпис": ПІДПИС_ЯДРА, "номер": None, "код": ""}]
        ф = self.розмір_функції
        for номер, функція in enumerate(self.функції):
            sx, sy = self.на_екран(функція["x"], функція["y"])
            вихід.append({"тип": "функція", "x": sx - ф / 2, "y": sy - ф / 2, "розмір": ф,
                          "колір": КОЛІР_ФУНКЦІЇ, "підпис": ПІДПИС_ФУНКЦІЇ, "номер": номер,
                          "код": функція["код"]})
        return вихід

    def що_в_точці(self, sx, sy):
        """("функція", номер), ("ядро", None) або None — верхній квадрат під
        точкою екрана; межі включно."""
        for кв in reversed(self.квадрати()):
            if кв["x"] <= sx <= кв["x"] + кв["розмір"] and кв["y"] <= sy <= кв["y"] + кв["розмір"]:
                return кв["тип"], кв["номер"]
        return None

    # ---- палець --------------------------------------------------------------

    def дотик_униз(self, sx, sy):
        self._дотик = {"початок": (float(sx), float(sy)), "останнє": (float(sx), float(sy)),
                       "ціль": self.що_в_точці(sx, sy), "тягнення": False}

    def дотик_рух(self, sx, sy):
        """Істина, якщо щось зрушило (треба перемалювати)."""
        д = self._дотик
        if д is None:
            return False
        if not д["тягнення"]:
            if math.hypot(sx - д["початок"][0], sy - д["початок"][1]) <= self.поріг_руху:
                return False
            д["тягнення"] = True
            д["останнє"] = д["початок"]      # перший зсув — від самого початку, без стрибка
        dx, dy = sx - д["останнє"][0], sy - д["останнє"][1]
        д["останнє"] = (float(sx), float(sy))
        if д["ціль"] and д["ціль"][0] == "функція":
            функція = self.функції[д["ціль"][1]]
            функція["x"] += dx
            функція["y"] += dy
        else:
            self.зсув = (self.зсув[0] + dx, self.зсув[1] + dy)
        return True

    def дотик_вгору(self, sx, sy):
        """Дія: ("додано", номер), ("відкрити", номер) або None."""
        д = self._дотик
        if д is None:
            return None
        if д["тягнення"]:
            self.дотик_рух(sx, sy)      # останній відрізок тягнення
            self._дотик = None
            return None
        self._дотик = None
        ціль = д["ціль"]
        if ціль is None:
            x, y = self.з_екрана(*д["початок"])
            self.функції.append({"x": x, "y": y, "код": ""})
            return "додано", len(self.функції) - 1
        if ціль[0] == "функція":
            return "відкрити", ціль[1]
        return None

    def дотик_скасовано(self):
        self._дотик = None

    # ---- код функцій ---------------------------------------------------------

    def код(self, номер):
        return self.функції[номер]["код"]

    def записати_код(self, номер, текст):
        self.функції[номер]["код"] = текст


def перший_рядок(код, найбільше=12):
    """Короткий показ коду на квадраті: перший непорожній рядок, обрізаний."""
    for рядок in код.splitlines():
        рядок = рядок.strip()
        if рядок:
            return рядок if len(рядок) <= найбільше else рядок[: найбільше - 1] + "…"
    return ""


def колір_rgb(hex_колір):
    """'#rrggbb' -> (r, g, b) у 0..1 для Kivy."""
    h = hex_колір.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
